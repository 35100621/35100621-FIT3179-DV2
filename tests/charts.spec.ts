import {test,expect} from '@playwright/test'
test('twelve charts, coordinated controls and responsive layout',async({page},info)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(String(e)))
 page.on('console',m=>{if(m.type()==='warn'||m.type()==='error')errors.push(m.text())})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('./');await expect(page.locator('[data-ready=true]')).toHaveCount(12)
 await expect(page.locator('.chart-error')).toHaveCount(0)
 await expect(page.locator('[data-chart=population-pyramid] .mark-rect path')).toHaveCount(36)
 await expect(page.locator('[data-chart=provider-treemap] .mark-rect path')).toHaveCount(4)
 await expect(page.locator('[data-chart=capacity-cartogram] .capacity_shapes_marks path')).toHaveCount(16)
 await page.locator('#state-search').fill('Pulau Pinang')
 await expect(page.locator('[data-insight=rank]')).toContainText('Pulau Pinang')
 await expect(page.locator('[data-insight=rank]')).toContainText('Pulau Pinang')
 await page.getByLabel('Select year',{exact:true}).fill('2015')
 await expect(page.locator('.year-readout')).toContainText('100.00')
 await page.getByRole('button',{name:'Public only',exact:true}).count().then(async n=>{if(!n)await page.getByRole('button',{name:'Combined',exact:true}).click()})
 await page.getByRole('button',{name:'Reset ranks',exact:true}).click()
 await expect(page.getByRole('button',{name:'Reveal combined ranks'})).toBeVisible()
 await page.getByRole('button',{name:'Share (%)',exact:true}).click()
 await page.getByRole('button',{name:'2015',exact:true}).click()
 await expect(page.locator('[data-chart=population-pyramid]')).toHaveAttribute('aria-label',/2015/)
 await page.getByRole('button',{name:'Geography',exact:true}).click()
 await expect(page.locator('[data-chart=capacity-cartogram] .capacity_shapes_marks path')).toHaveCount(16)
 await page.getByRole('button',{name:'Capacity',exact:true}).click()
 await page.getByRole('button',{name:'Open chapter overview'}).click()
 await expect(page.locator('.chapter-overview')).toBeVisible()
 await page.locator('.chapter-overview a').nth(2).click()
 await expect(page.locator('.chapter-overview')).toBeHidden()
 await page.getByRole('button',{name:'Reset selection',exact:true}).click()
 await page.getByRole('button',{name:'Public only',exact:true}).click()
 await page.getByRole('button',{name:'Reveal combined ranks'}).click()
 await page.getByRole('button',{name:'2024',exact:true}).click()
 await page.locator('[data-chart=provider-treemap] .mark-rect path').first().hover({position:{x:10,y:10}})
 await expect(page.locator('#vg-tooltip-element')).toContainText('Reported admissions')
 await page.mouse.move(0,0)
 const layout=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,charts:[...document.querySelectorAll('[data-chart]')].map(e=>({id:e.getAttribute('data-chart'),w:e.getBoundingClientRect().width,svg:e.querySelector('svg')!.getBoundingClientRect().width}))}))
 expect(layout.scroll).toBeLessThanOrEqual(layout.width)
 for(const c of layout.charts)expect(c.svg,JSON.stringify(c)).toBeLessThanOrEqual(c.w+1)
 await page.screenshot({path:`test-results/${info.project.name}-latest-full.png`,fullPage:true})
 for(const id of ['act-2','act-3','act-5','act-6'])await page.locator(`#${id}`).screenshot({path:`test-results/${info.project.name}-${id}.png`})
 expect(errors).toEqual([])
})
