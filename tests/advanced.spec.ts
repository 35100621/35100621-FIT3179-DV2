import {test,expect} from '@playwright/test'
test('advanced views preserve quantities, interactions and reduced-motion readability',async({page},testInfo)=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 const errors:string[]=[];page.on('pageerror',e=>errors.push(String(e)))
 page.on('console',m=>{if(m.type()==='warn'||m.type()==='error')errors.push(m.text())})
 await page.goto('./');await expect(page.locator('[data-ready=true]')).toHaveCount(12)
 await expect(page.locator('.chart-error')).toHaveCount(0)
 await expect(page.locator('[data-chart=population-pyramid] .mark-rect path')).toHaveCount(72)
 await expect(page.locator('[data-chart=provider-treemap] .mark-rect path')).toHaveCount(4)
 const map=page.locator('[data-chart=ageing-cartogram] .mark-path').nth(1).locator('path')
 await expect(map).toHaveCount(16)
 await page.locator('#age-map-state').selectOption('Perak')
 await expect(page.locator('.demographic-map .state-readout')).toContainText('254,600')
 await expect(page.locator('.demographic-map .state-readout')).toContainText('9.91%')
 await expect(map).toHaveCount(16)
 await page.locator('#age-map-state').selectOption('')
 await page.locator('#age-map-region').selectOption('East Malaysia')
 await expect(map).toHaveCount(3)
 await page.locator('#age-map-state').selectOption('W.P. Labuan')
 await expect(page.locator('.demographic-map .state-readout')).toContainText('5,200')
 await page.locator('#age-map-region').selectOption('All Malaysia')
 await page.locator('#age-map-state').selectOption('')
 await expect(map).toHaveCount(16)
 await page.locator('.provider-treemap summary').click()
 await expect(page.locator('.provider-treemap tbody')).toContainText('5,646')
 await expect(page.locator('.provider-treemap tbody')).toContainText('19,920')
 await page.locator('.provider-treemap summary').click()
 await page.locator('[data-chart=provider-treemap] .mark-rect path').first().hover()
 await expect(page.locator('#vg-tooltip-element')).toContainText('Beds')
 await page.mouse.move(0,0)
 const layout=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,charts:[...document.querySelectorAll('[data-chart]')].map(e=>({w:e.getBoundingClientRect().width,svg:e.querySelector('svg')!.getBoundingClientRect().width}))}))
 expect(layout.scroll).toBeLessThanOrEqual(layout.width)
 for(const c of layout.charts)expect(c.svg).toBeLessThanOrEqual(c.w+1)
 for(const id of ['provider-treemap','population-pyramid','ageing-cartogram'])await page.locator(`[data-chart=${id}]`).screenshot({path:`test-results/${testInfo.project.name}-${id}.png`})
 expect(errors).toEqual([])
})
